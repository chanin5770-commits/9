#!/usr/bin/env python3
"""Analyzes assets/song/song.mp3 for the music video (src/song.js).

Writes assets/song/analysis.js with per-frame (30fps) loudness, bass, highs and
onset strength (all 0..1), plus the tempo and the beat grid.
Needs ffmpeg and numpy.
"""
import json, subprocess, sys
import numpy as np

SRC, OUT, FPS, SR = 'assets/song/song.mp3', 'assets/song/analysis.js', 30, 22050

raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', SRC, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
                     check=True, capture_output=True).stdout
a = np.frombuffer(raw, dtype=np.float32)
dur = len(a) / SR

hop, win = 256, 2048
n = (len(a) - win) // hop
idx = np.arange(win)[None, :] + hop * np.arange(n)[:, None]
X = np.abs(np.fft.rfft(a[idx] * np.hanning(win), axis=1))
freqs = np.fft.rfftfreq(win, 1 / SR)
fr = SR / hop
t = (np.arange(n) * hop + win / 2) / SR

L = np.log1p(X * 10)
flux = np.r_[0, np.maximum(0, np.diff(L, axis=0)).sum(1)]
onset = np.maximum(flux - np.convolve(flux, np.ones(32) / 32, 'same'), 0)

rms = np.sqrt((a[idx] ** 2).mean(1))
bass = X[:, (freqs > 30) & (freqs < 150)].mean(1)
high = X[:, freqs > 4000].mean(1)

# tempo: autocorrelation of the onset curve over the body of the song
seg = onset[int(10 * fr):int(min(dur - 10, 130) * fr)]
ac = np.correlate(seg, seg, 'full')[len(seg) - 1:]
A = lambda l: np.interp(l, np.arange(len(ac)), ac)
bpm = max(np.arange(70, 170, 0.05), key=lambda b: A(60 / b * fr) + 0.5 * A(120 / b * fr) + 0.5 * A(240 / b * fr))
bpm = round(bpm)  # studio tracks sit on whole BPMs
T = 60 / bpm
phase = max(np.arange(0, T, 0.002), key=lambda p: np.interp(np.arange(p, dur, T), t, onset).sum())

def norm(x, q=0.98):
    return np.clip(x / (np.quantile(x, q) + 1e-9), 0, 1)

ft = np.arange(int(dur * FPS)) / FPS
def per_frame(x, smooth):
    y = np.interp(ft, t, x)
    if smooth > 1:
        k = np.exp(-np.arange(smooth) / (smooth / 3)); k /= k.sum()  # fast attack, slow release
        y = np.convolve(y, k)[:len(y)]
    return [round(float(v), 3) for v in norm(y)]

data = {
    'dur': round(dur, 3), 'fps': FPS, 'bpm': bpm, 'beat0': round(float(phase), 3),
    'rms': per_frame(rms, 6), 'bass': per_frame(bass, 3), 'high': per_frame(high, 3), 'onset': per_frame(onset, 2),
}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/analyze-song.py — do not edit\nwindow.SONG_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f'{OUT}: {dur:.1f}s, {bpm} BPM, first beat {phase:.3f}s', file=sys.stderr)
