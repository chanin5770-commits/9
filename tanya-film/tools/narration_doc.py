pick = lambda txt, i: re.sub(r'\{([^|}]*)\|([^}]*)\}', lambda m: m.group(i), txt)
table_text = lambda t: pick(t, 1).replace('¶ ', '').replace('¶', '')
voice_text = lambda t: pick(t, 2)


def estimate(text):
    plain = voice_text(text).replace('¶', '').replace('//', ' ').replace('/', ' ')
    words = len(re.findall(r'[א-ת֑-ׇ״׳"]+', plain))
    pauses = text.count('//') * LONG + (text.count('/') - 2 * text.count('//')) * SHORT
    return words, words / WPS + pauses


rows, extra = [], {}
for sid, a, b, see, text, pause in SEGMENTS:
    win = b - a
    if text is None:
        rows.append((sid, a, b, see, '— שקט —', pause, None, win))
        continue
    words, est = estimate(text)
    need = est + 0.6  # מרווח נשימה בסוף הקטע
    if need > win:
        extra[sid] = extra.get(sid, 0) + (need - win)
    rows.append((sid, a, b, see, table_text(text).replace(' // ', ' … ').replace(' / ', ' '), pause, (words, est), win))

