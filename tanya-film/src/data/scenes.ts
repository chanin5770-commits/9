// כל התוכן של הסרט: סצנות, שוטים, טקסט מסך, קריינות והפניות למקור.
// המשך של כל סצנה מגיע מ-timing.json (כדי שאפשר יהיה לסנכרן לקריינות בלי לגעת כאן).
//
// מוסכמות:
// - shot.kind 'panel' = תמונת סטילס מונפשת (זום/פאן). src = שם הקובץ ב-public/panels.
//   להחלפה בתמונה איכותית: שומרים קובץ באותו שם (או משנים את src) — בלי לבנות את הסצנה מחדש.
// - shot.kind 'clip'  = קליפ וידאו אמיתי (Flow/Veo). src = שם הקובץ ב-public/clips.
//   להחלפת סטילס בקליפ: משנים kind ל-'clip' ואת src. משך קליפ נקבע לפי אורכו.
// - from/to: נקודת המיקוד (x,y בין 0 ל-1 ביחס לתמונה) וזום (1 = התמונה ממלאת את הפריים).
// - beat.at / beat.dur: חלק יחסי ממשך הסצנה (0–1), כך שהטקסטים זזים יחד עם שינוי משך הסצנה.
// - beat.kind:
//     question = השאלה שאיתה הדמות נכנסת לתחנה (משל/המחשה, לא ציטוט)
//     insight  = החידוש של הפרק, בניסוח שלנו (לא ציטוט; בלי מירכאות)
//     quote    = ציטוט מקור (מוצג במירכאות + מקור). verify=true => דורש אימות מול מהדורה מודפסת
//     message  = המסר האישי של הדמות (פרשנות/יישום, לא דברי התניא)
// - narration: טקסט הקריינות לסצנה. ריק עד שהרצף מאושר.

export type Move = { x: number; y: number; z: number };

export type Shot =
  | { kind: 'panel'; src: string; w: number; from: Move; to: Move }
  | { kind: 'clip'; src: string; from?: Move; to?: Move };

export type Beat = {
  kind: 'title' | 'question' | 'insight' | 'quote' | 'message' | 'ref';
  text: string;
  at: number;
  dur: number;
  source?: string;
  verify?: boolean;
};

export type Scene = {
  id: string;
  title: string;
  gate?: number;
  station?: number;
  chapter?: string;
  tone: number; // -1 קר וכחול ... 1 חם וזהוב
  transition: 'black' | 'cross';
  shots: Shot[];
  beats: Beat[];
  overlay?: 'map' | 'finale';
  contentRef: string;
  narration: string;
};

