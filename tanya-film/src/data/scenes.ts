// משך שוט לא יורד מזמן הקריאה של הטקסט שעליו (ראו src/lib/reading.ts)
const S = (src: string, sec: number, move: Move = 'in', o: Common = {}): StillShot => ({ kind: 'still', src, sec: o.text ? Math.max(sec, readSec(o.text) + 0.4) : sec, move, ...o });
const C = (src: string, o: Common & { maxSec?: number; move?: Move } = {}): ClipShot => ({ kind: 'clip', src, ...o });
const G = (g: string, sec: number, o: Omit<GraphicShot, 'kind' | 'g' | 'sec'> = {}): GraphicShot => {
  const need = (o.lines ?? []).reduce((a, t) => a + readSec(t), 0);
  const intro = g === 'text' || g === 'verse' ? 0.5 : g === 'crossroads' ? 3 : 2.5;
  return { kind: 'graphic', g, sec: Math.max(sec, intro + need), fade: 12, ...o };
};
const GATE = (gate: number, bg: string): GateShot => ({ kind: 'gate', gate, sec: 6.5, bg, fade: 14, sfx: [{ id: 'low-hit', vol: 0.5 }, { id: 'whoosh', at: 0.1, vol: 0.4 }] });
