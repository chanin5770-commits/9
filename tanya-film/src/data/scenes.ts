const W = (x: number, y: number, z: number): Move => ({ x, y, z });
const wide = (src: string, w = 3, z1 = 1.07): Shot => ({ kind: 'panel', src, w, from: W(0.5, 0.5, 1), to: W(0.5, 0.5, z1) });
const push = (src: string, x: number, y: number, z0: number, z1: number, w = 3): Shot => ({ kind: 'panel', src, w, from: W(x, y, z0), to: W(x, y, z1) });
const pan = (src: string, a: Move, b: Move, w = 2): Shot => ({ kind: 'panel', src, w, from: a, to: b });
const clip = (src: string): Shot => ({ kind: 'clip', src, from: W(0.5, 0.5, 1.0), to: W(0.5, 0.5, 1.04) });

